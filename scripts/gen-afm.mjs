// Generates crates/ihp-core/src/afm.rs: WinAnsi widths (codes 32..255) of the 12 standard fonts, from pdf-lib's AFM data.
import { PDFDocument, StandardFonts } from 'pdf-lib';
import { writeFileSync } from 'node:fs';

const names = ['Helvetica', 'HelveticaBold', 'HelveticaOblique', 'HelveticaBoldOblique', 'TimesRoman', 'TimesRomanBold', 'TimesRomanItalic', 'TimesRomanBoldItalic', 'Courier', 'CourierBold', 'CourierOblique', 'CourierBoldOblique'];
const dec = new TextDecoder('windows-1252');
const doc = await PDFDocument.create();
const kerns = [];
let out = '// Generated by scripts/gen-afm.mjs from pdf-lib\'s standard-font AFM data. Do not edit.\n';
out += '/// (BaseFont name, widths for WinAnsi codes 32..=255 in 1/1000 em (0 = no glyph), ascender in 1/1000 em)\n';
out += 'pub const FONTS: [(&str, [u16; 224], u16); 12] = [\n';
for (const n of names) {
  const font = await doc.embedFont(StandardFonts[n]);
  const w = [];
  for (let code = 32; code <= 255; code++) {
    const ch = dec.decode(Uint8Array.of(code));
    let width = 0;
    // 0x81, 0x8D, 0x8F, 0x90, 0x9D are undefined in WinAnsi
    if (![0x81, 0x8d, 0x8f, 0x90, 0x9d].includes(code)) {
      try { width = Math.round(font.widthOfTextAtSize(ch, 1000)); } catch { width = 0; }
    }
    w.push(width);
  }
  // Kerning pairs, as pdf-lib applies them when measuring text (nonzero only).
  const pairs = [];
  for (let a = 32; a <= 255; a++) {
    if (!w[a - 32]) continue;
    const ca = dec.decode(Uint8Array.of(a));
    for (let b = 32; b <= 255; b++) {
      if (!w[b - 32]) continue;
      const k = Math.round(font.widthOfTextAtSize(ca + dec.decode(Uint8Array.of(b)), 1000)) - w[a - 32] - w[b - 32];
      if (k) pairs.push(`(${(a << 8) | b}, ${k})`);
    }
  }
  kerns.push(pairs);
  const asc = Math.round(font.heightAtSize(1000, { descender: false }));
  out += `    ("${StandardFonts[n]}", [${w.join(', ')}], ${asc}),\n`;
}
out += '];\n\n/// Kerning pairs per font: ((left << 8) | right, adjustment in 1/1000 em), sorted by key.\n';
out += 'pub static KERNS: [&[(u16, i16)]; 12] = [\n';
for (const k of kerns) out += `    &[${k.join(', ')}],\n`;
out += '];\n';
writeFileSync('crates/ihp-core/src/afm.rs', out);
console.log('wrote crates/ihp-core/src/afm.rs');
